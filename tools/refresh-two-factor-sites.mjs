#!/usr/bin/env node
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const sourceUrl = 'https://2fa.directory/api/v4/all.json'
const attribution = 'Data sourced from 2FA Directory by 2factorauth (https://2fa.directory). License: MIT.'
const output = join(root, 'src-tauri', 'sesame-core', 'src', 'two_factor_sites.rs')
const minimumSites = 1_000

const domainPattern = /^[a-z0-9][a-z0-9.-]*\.[a-z0-9-]+$/

const response = await fetch(sourceUrl, { headers: { accept: 'application/json' } })
if (!response.ok) throw new Error(`The 2FA Directory request failed with status ${response.status}.`)
const payload = await response.json()
if (payload === null || typeof payload !== 'object' || Array.isArray(payload)) {
  throw new Error('The 2FA Directory response is not the expected object of sites.')
}

const domains = new Set()
for (const [rawDomain, entry] of Object.entries(payload)) {
  if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) continue
  if (!Array.isArray(entry.methods) || entry.methods.length === 0) continue
  const domain = rawDomain.trim().toLowerCase()
  if (!domainPattern.test(domain)) throw new Error(`The 2FA Directory returned an unexpected host: ${rawDomain}`)
  domains.add(domain)
}

const sorted = [...domains].sort()
if (sorted.length < minimumSites) {
  throw new Error(`Only ${sorted.length} sites came back, below the ${minimumSites} floor; refusing to shrink the list.`)
}

const retrieved = new Date().toISOString().slice(0, 10)
const lines = [
  '// Generated by tools/refresh-two-factor-sites.mjs. Do not edit by hand.',
  `// Source: ${sourceUrl}`,
  `// ${attribution}`,
  `// Retrieved: ${retrieved}. Sites with a documented 2FA or passkey method.`,
  '',
  `pub static TWO_FACTOR_SITES: [&str; ${sorted.length}] = [`,
  ...sorted.map((domain) => `    "${domain}",`),
  '];',
  '',
]
writeFileSync(output, lines.join('\n'))
console.log(`Wrote ${sorted.length} sites to ${output}`)
